"""Turn data/fighters.json into src/ReplicatedStorage/Shared/Fighters.luau.

Edit fighter stats, looks and ability text in data/fighters.json, then run:
    python3 tools/build_fighters.py
(from the game/ folder). The ability *code* lives in
src/ServerScriptService/Sim/Abilities/<id>.luau.

fighters.json is a list of objects like:
{
  "id": "saiyan",                       # code id, lowercase letters/numbers/underscore
  "name": "Saiyan Hero",                 # in-game (parody) name
  "inspiredBy": "Goku — Dragon Ball",    # for reference only, never shown in-game
  "rarity": "Mythic",                    # Rare | Epic | Legendary | Mythic
  "role": "Bruiser",
  "tagline": "One short line shown on the pick card",
  "stats": {"hp": 520, "speed": 22, "size": 5.5, "contactDamage": 8, "mass": 1.1},
  "look": {"skin": "#f5cfa6", "outfit": "#ff7a00", "outfit2": "#1f3fbf", "hair": "#111111",
           "hairStyle": "spiky", "eyes": "#1b1b1b", "aura": "#ffd93b",
           "accessories": ["gloves"], "accessoryColor": "#3355ff"},
  "ability1": {"name": "Energy Wave", "description": "...", "cooldown": 6, "color": "#5fd3ff"},
  "ability2": {"name": "Ultra Instinct Rush", "description": "...", "color": "#e8f6ff"},
  "summonable": true
}
"""

import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.dirname(HERE)
SRC = os.path.join(GAME, "data", "fighters.json")
OUT = os.path.join(GAME, "src", "ReplicatedStorage", "Shared", "Fighters.luau")

RARITIES = ["Rare", "Epic", "Legendary", "Mythic"]
HAIR = {"spiky", "wild", "messy", "short", "long", "twintails", "ponytail", "slick", "bowl", "bun", "bald"}


def lua(v, indent=1):
    pad = "\t" * indent
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v) if isinstance(v, float) else str(v)
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, list):
        return "{ " + ", ".join(lua(x, indent + 1) for x in v) + " }"
    if isinstance(v, dict):
        items = []
        for k, x in v.items():
            key = k if re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", k) else "[" + json.dumps(k) + "]"
            items.append(f"{pad}\t{key} = {lua(x, indent + 1)},")
        return "{\n" + "\n".join(items) + f"\n{pad}}}"
    if v is None:
        return "nil"
    raise TypeError(type(v))


def validate(f):
    errs = []
    if not re.match(r"^[a-z][a-z0-9_]*$", f.get("id", "")):
        errs.append("bad id")
    if f.get("rarity") not in RARITIES:
        errs.append("bad rarity")
    st = f.get("stats", {})
    for k in ("hp", "speed", "size", "contactDamage"):
        if not isinstance(st.get(k), (int, float)):
            errs.append(f"stats.{k} missing")
    if f.get("look", {}).get("hairStyle") not in HAIR:
        errs.append("unknown hairStyle " + str(f.get("look", {}).get("hairStyle")))
    for slot in ("ability1", "ability2"):
        a = f.get(slot)
        if not a or not a.get("name"):
            errs.append(f"{slot} missing")
    if not isinstance(f.get("ability1", {}).get("cooldown"), (int, float)):
        errs.append("ability1.cooldown missing")
    return errs


def main():
    with open(SRC) as fh:
        fighters = json.load(fh)
    ids = set()
    bad = False
    for f in fighters:
        errs = validate(f)
        if f.get("id") in ids:
            errs.append("duplicate id")
        ids.add(f.get("id"))
        if errs:
            bad = True
            print(f"{f.get('id')}: " + "; ".join(errs), file=sys.stderr)
    if bad:
        sys.exit(1)

    lines = [
        "--!strict",
        "-- GENERATED by tools/build_fighters.py from data/fighters.json. Edit the JSON, not this file.",
        "-- Ability code: ServerScriptService/Sim/Abilities/<id>.luau",
        "",
        "local Fighters = {}",
        "",
        "Fighters.List = {",
    ]
    for f in fighters:
        entry = {k: f[k] for k in ("id", "name", "rarity", "role", "tagline", "stats", "look", "ability1", "ability2") if k in f}
        entry["summonable"] = f.get("summonable", True)
        entry["order"] = fighters.index(f) + 1
        lines.append("\t-- " + f.get("inspiredBy", "").replace("\n", " "))
        lines.append("\t" + lua(entry, 1) + ",")
    lines += [
        "}",
        "",
        "Fighters.ById = {}",
        "for _, f in Fighters.List do",
        "\tFighters.ById[f.id] = f",
        "end",
        "",
        "function Fighters.get(id: string)",
        "\treturn Fighters.ById[id]",
        "end",
        "",
        "-- all fighter ids of one rarity",
        "function Fighters.ofRarity(rarity: string): { string }",
        "\tlocal out = {}",
        "\tfor _, f in Fighters.List do",
        "\t\tif f.rarity == rarity and f.summonable then",
        "\t\t\ttable.insert(out, f.id)",
        "\t\tend",
        "\tend",
        "\treturn out",
        "end",
        "",
        "return Fighters",
        "",
    ]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {len(fighters)} fighters to {os.path.relpath(OUT, GAME)}")


if __name__ == "__main__":
    main()
